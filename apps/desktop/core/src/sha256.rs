//! SHA-256 (FIPS 180-4), for the update's archive (update_flow `update_archive_line`): the shell tells the server the
//! digest of the bytes the updater verified, and the server hashes the kept file again before it reads the new
//! version's Tools from it (DESIGN §4p (d)). Pure Rust, no dependency (desktop-core has none: no crate, no Cargo.lock
//! change); its tests are the standard's own vectors.

