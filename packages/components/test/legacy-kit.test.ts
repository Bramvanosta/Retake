/**
 * old-name: this whole file (the guard test allows it).
 *
 * L5.13 — a person's own components and READMEs written before the rename:
 * - a component that imports the kit under its old specifier is refused with the new one named (no alias: D2);
 * - a README's generated block written before the rename (its begin marker named the command of that time) is
 *   replaced, never doubled (D0).
 */
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { KIT_MODULE, README_BEGIN, README_END, importProblem, mergePreviewReadme } from '../src/index.js';

describe('the kit under its old specifier', () => {
  it('is refused, naming the new specifier', () => {
    const dir = join(tmpdir(), 'acme', 'card');
    expect(importProblem('@demo-studio/components/kit', dir, dir)).toBe('import "@demo-studio/components/kit" is the kit\'s name before L5.13: import "@retake/components/kit"');
    expect(importProblem(KIT_MODULE, dir, dir)).toBeUndefined();
  });
});

describe("a README's block from before the rename", () => {
  it('is found by its begin marker whatever the rest of the comment says, and replaced', () => {
    const old = [
      '<!-- studio:component-preview:begin (generated by `studio components preview`; edit component.yaml instead) -->',
      '# Old card',
      README_END,
      '',
      'Notes the author wrote.',
    ].join('\n');
    const block = `${README_BEGIN}\n# New card\n${README_END}`;
    const merged = mergePreviewReadme(old, block);
    expect(merged).toBe(`${block}\n\nNotes the author wrote.`);
    expect(merged.match(/component-preview:begin/g)).toHaveLength(1);
  });
});
